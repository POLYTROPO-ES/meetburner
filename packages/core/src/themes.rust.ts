import type { Theme } from './themes';

/** Rust file that mirrors themes.ts for the camera renderer (ADR-0014). */
export const RUST_THEMES_PATH = '../../../apps/desktop/src-tauri/src/camera/themes_data.rs';

const FONT_VARIANTS: Record<string, string> = {
  system: 'System',
  serif: 'Serif',
  mono: 'Mono',
  rounded: 'Rounded',
  condensed: 'Condensed',
  handwritten: 'Handwritten',
  display: 'Display',
};

const PLATE_VARIANTS: Record<Theme['plates'], string> = { none: 'None', flap: 'Flap' };

function rgb(hex: string): string {
  const value = hex.replace('#', '');
  if (!/^[0-9a-f]{6}$/i.test(value)) throw new Error(`not a #rrggbb colour: ${hex}`);
  const parts = [0, 2, 4].map((i) => `0x${value.slice(i, i + 2).toLowerCase()}`);
  return `(${parts.join(', ')})`;
}

function font(id: string): string {
  const variant = FONT_VARIANTS[id];
  if (!variant) throw new Error(`unknown font id: ${id}`);
  return `FontId::${variant}`;
}

function plates(style: Theme['plates']): string {
  const variant = PLATE_VARIANTS[style];
  if (!variant) throw new Error(`unknown plate style: ${style}`);
  return `PlateStyle::${variant}`;
}

function escape(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** Renders the Rust mirror of the shared themes. Deterministic: themes are sorted by id. */
export function renderRustThemes(themes: Record<string, Theme>): string {
  const lines = [
    '// @generated by tools/gen-themes.mts from packages/core/src/themes.ts — do not edit.',
    '// Run `npm run gen:themes` after changing themes.ts; a Vitest test fails if this file is stale.',
    '',
    'use super::{FontId, PlateStyle, Theme};',
    '',
    '// Kept exactly as generated: rustfmt must not reflow the data table.',
    '#[rustfmt::skip]',
    'pub static THEMES: &[(&str, Theme)] = &[',
  ];
  for (const id of Object.keys(themes).sort()) {
    const theme = themes[id];
    lines.push(
      `    (`,
      `        "${id}",`,
      `        Theme {`,
      `            background: ${rgb(theme.background)},`,
      `            background_alt: ${rgb(theme.backgroundAlt)},`,
      `            text: ${rgb(theme.text)},`,
      `            muted: ${rgb(theme.muted)},`,
      `            accent: ${rgb(theme.accent)},`,
      `            font: ${font(theme.font)},`,
      `            weight: ${theme.weight.toFixed(1)},`,
      `            radius: ${theme.radius.toFixed(1)},`,
      `            decoration: "${escape(theme.decoration)}",`,
      `            plates: ${plates(theme.plates)},`,
      `        },`,
      `    ),`,
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}
